export const dictionaries: Record<Lang, Record<TranslationKey, string>> = { tr, en };

/** t("sign.codeSent", { phone: "0555..." }) */
export const translate = (lang: Lang, key: TranslationKey, params?: Record<string, string | number>) => {
  let text: string = dictionaries[lang][key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
};

export const formatDate = (lang: Lang, value?: string, withTime = false) =>
  value
    ? new Date(value).toLocaleString(lang === "en" ? "en-GB" : "tr-TR", {
        day: "2-digit",
        month: "short",
        year: "numeric",
        ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
      })
    : "-";

/**
 * Composable for components: t() and formatDate() follow the language in the
 * preferences store, so every text updates as soon as the language changes.
 */
export function useI18n() {
  const preferences = usePreferencesStore()
  const lang = computed(() => preferences.lang)
  const t = (key: TranslationKey, params?: Record<string, string | number>) =>
    translate(preferences.lang, key, params)
  const date = (value?: string, withTime = false) => formatDate(preferences.lang, value, withTime)
  return { lang, t, formatDate: date }
}
